#!/usr/bin/env python3
"""extract_vocab.py — Extract SentencePiece vocab from GGUF metadata.
Produces bqsm_vocab.h with sorted token array for greedy longest-match.
Each token stored as {uint16_t len; char bytes[len]} with binary-search index."""
import struct, sys
from gguf import GGUFReader

GGUF_PATH = "/home/compunerd/Downloads/gemma-2-2b-it-abliterated-Q4_K_M.gguf"
OUT_H = "bqsm_vocab.h"

reader = GGUFReader(GGUF_PATH)

# Read tokenizer metadata
tokens = None
scores = None
for field in reader.fields.values():
    if field.name == "tokenizer.ggml.tokens":
        # Array of strings
        tokens = field.parts[field.data[0]]
        if hasattr(tokens, 'tolist'):
            tokens = [bytes(t).decode('utf-8', errors='replace') for t in tokens]
    elif field.name == "tokenizer.ggml.scores":
        pass  # not needed for greedy

if not tokens:
    print("ERROR: tokenizer.ggml.tokens not found in GGUF", file=sys.stderr)
    sys.exit(1)

vocab_size = len(tokens)
print(f"Vocabulary: {vocab_size} tokens")

# Create (token_string, id) pairs
vocab = [(s, i) for i, s in enumerate(tokens)]

# Sort by token string for binary search
vocab.sort(key=lambda x: x[0])

# Convert to bytes (use utf-8, escape null bytes)
token_bytes = []
offsets = []
offset = 0
for s, tid in vocab:
    b = s.encode('utf-8', errors='replace')
    # Escape or handle null bytes: replace with \x00 representation
    # For simplicity, keep raw bytes — the C code uses memcmp with explicit length
    token_bytes.append(b)
    offsets.append((offset, len(b), tid))
    offset += len(b)

total_bytes = offset
print(f"Total token bytes: {total_bytes:,}")

# Write C header
with open(OUT_H, 'w') as f:
    f.write(f"""/* Auto-generated by extract_vocab.py — SentencePiece vocab for Gemma 2B
 * {vocab_size} tokens, {total_bytes:,} bytes, sorted for binary search.
 * Each entry: uint16_t len, char data[len]. Binary search by (data, len).
 * Result is the original token ID. */
#ifndef BQSM_VOCAB_H
#define BQSM_VOCAB_H

#define SP_VOCAB_SIZE {vocab_size}
#define SP_VOCAB_DATA_LEN {total_bytes}

""")
    
    # Write the token data as a byte array
    f.write("static const unsigned char sp_vocab_data[] = {\n")
    for i, b in enumerate(token_bytes):
        # 2-byte length
        f.write(f"  {len(b) & 0xFF}, {(len(b) >> 8) & 0xFF},")
        # Token bytes
        for j, byte in enumerate(b):
            if j % 16 == 0:
                f.write("\n   ")
            f.write(f" {byte},")
        f.write("\n")
    f.write("};\n\n")
    
    # Write the offset table: uint32_t offset, uint32_t token_id
    f.write(f"// Offsets: {{uint32_t data_offset, uint32_t token_id}} — sorted alphabetically\n")
    f.write(f"static const uint32_t sp_vocab_offsets[{vocab_size}][2] = {{\n")
    for off, length, tid in offsets:
        f.write(f"  {{{off}U, {tid}U}},\n")
    f.write("};\n\n")
    
    f.write("#endif /* BQSM_VOCAB_H */\n")

# Also write a binary lookup table: for each token string, write offset in data array
# Binary search: compare token at offsets[idx] with input substring
# Use memcmp with explicit length

print(f"Wrote {OUT_H} ({len(token_bytes)} entries)")
print(f"Sample tokens: {[(s[:20], tid) for s, tid in vocab[:10]]}")
print(f"Sample tokens (end): {[(s[:20], tid) for s, tid in vocab[-5:]]}")
